create or replace function public.buy_item(target_item bigint)
returns jsonb language plpgsql security definer set search_path='public' as $$
declare p public.profiles; it public.items;
begin
 if auth.uid() is null then raise exception 'not authenticated'; end if;
 select * into p from public.profiles where id=auth.uid() for update;
 select * into it from public.items where id=target_item;
 if it.id is null then raise exception 'Няма такъв предмет'; end if;
 if p.level < it.min_level then raise exception 'Нивото ти е ниско'; end if;
 if p.money < it.price then raise exception 'Нямаш достатъчно пари'; end if;
 if it.item_type<>'consumable' and not it.consumed_on_use and exists(select 1 from public.inventory where user_id=auth.uid() and item_id=target_item) then raise exception 'Вече имаш този предмет'; end if;
 update public.profiles set money=money-it.price where id=auth.uid();
 insert into public.inventory(user_id,item_id,quantity) values(auth.uid(),target_item,1)
 on conflict(user_id,item_id) do update set quantity=public.inventory.quantity+1;
 insert into public.action_log(user_id,action_type,message,money_change,respect_change) values(auth.uid(),'shop','Купи '||it.name,-it.price,0);
 return jsonb_build_object('ok',true,'item',it.name);
end $$;

create or replace function public.fight_player(opponent uuid,p_weapon_item_id bigint)
returns jsonb language plpgsql security definer set search_path='public' as $$
declare
 a public.profiles; d public.profiles; act public.activities; weapon public.items; defender_weapon public.items;
 weapon_qty int:=0; a_str int; a_def int; a_luck int; d_str int; d_def int; d_luck int;
 ascore numeric; dscore numeric; won boolean; rep int; cash int; bid bigint; burn_damage int:=0; effect text:=null;
begin
 if auth.uid() is null then raise exception 'not authenticated'; end if;
 if opponent=auth.uid() then raise exception 'Не можеш да нападнеш себе си'; end if;
 select * into act from public.activities where user_id=auth.uid();
 if act.user_id is not null then
  if act.ends_at<=now() then raise exception 'Имаш приключила дейност. Вземи наградата първо.'; else raise exception 'Не можеш да се биеш, докато героят е зает.'; end if;
 end if;
 perform public.regen_me();
 select * into a from public.profiles where id=auth.uid() for update;
 select * into d from public.profiles where id=opponent for update;
 if d.id is null then raise exception 'Играчът не съществува'; end if;
 if a.energy<20 then raise exception 'Нямаш достатъчно енергия'; end if;
 if p_weapon_item_id is not null then
  select i.* into weapon from public.inventory v join public.items i on i.id=v.item_id where v.user_id=a.id and v.item_id=p_weapon_item_id and i.item_type='weapon';
  if weapon.id is null then raise exception 'Не притежаваш това оръжие'; end if;
  select quantity into weapon_qty from public.inventory where user_id=a.id and item_id=weapon.id for update;
 end if;
 select a.strength+coalesce(sum(i.strength_bonus+i.attack_bonus),0),a.defense+coalesce(sum(i.defense_bonus),0),a.luck+coalesce(sum(i.luck_bonus),0)
 into a_str,a_def,a_luck from public.inventory v join public.items i on i.id=v.item_id where v.user_id=a.id and v.equipped=true and (p_weapon_item_id is null or i.slot<>'weapon' or i.id=p_weapon_item_id);
 if a_str is null then a_str:=a.strength; a_def:=a.defense; a_luck:=a.luck; end if;
 if weapon.id is not null and not exists(select 1 from public.inventory where user_id=a.id and item_id=weapon.id and equipped=true) then
  a_str:=a_str+weapon.strength_bonus+weapon.attack_bonus; a_def:=a_def+weapon.defense_bonus; a_luck:=a_luck+weapon.luck_bonus;
 end if;
 select i.* into defender_weapon from public.inventory v join public.items i on i.id=v.item_id where v.user_id=d.id and v.equipped=true and i.item_type='weapon' order by i.attack_bonus desc limit 1;
 select d.strength+coalesce(sum(i.strength_bonus+i.attack_bonus),0),d.defense+coalesce(sum(i.defense_bonus),0),d.luck+coalesce(sum(i.luck_bonus),0)
 into d_str,d_def,d_luck from public.inventory v join public.items i on i.id=v.item_id where v.user_id=d.id and v.equipped=true;
 if d_str is null then d_str:=d.strength; d_def:=d.defense; d_luck:=d.luck; end if;
 ascore:=a_str*1.5+a_def+a_luck*0.7+random()*18; dscore:=d_str*1.5+d_def+d_luck*0.7+random()*18;
 if weapon.combat_effect='burn' then effect:='burn'; burn_damage:=greatest(1,weapon.combat_effect_value); ascore:=ascore+burn_damage; end if;
 won:=ascore>=dscore; update public.profiles set energy=energy-20 where id=a.id;
 if won then
  rep:=4+floor(random()*5)::int; cash:=5+floor(random()*8)::int;
  update public.profiles set wins=wins+1,respect=respect+rep,money=money+cash where id=a.id;
  update public.profiles set losses=losses+1,hp=greatest(10,hp-10-burn_damage) where id=d.id;
  insert into public.battles(attacker,defender,winner,respect_change,money_change,attacker_weapon_id,defender_weapon_id,attacker_score,defender_score,special_effect,details)
  values(a.id,d.id,a.id,rep,cash,weapon.id,defender_weapon.id,round(ascore,1),round(dscore,1),effect,jsonb_build_object('energy_cost',20,'burn_damage',burn_damage)) returning id into bid;
 else
  rep:=0; cash:=0;
  update public.profiles set losses=losses+1,hp=greatest(10,hp-15) where id=a.id;
  update public.profiles set wins=wins+1,respect=respect+2,hp=greatest(10,hp-burn_damage) where id=d.id;
  insert into public.battles(attacker,defender,winner,respect_change,money_change,attacker_weapon_id,defender_weapon_id,attacker_score,defender_score,special_effect,details)
  values(a.id,d.id,d.id,0,0,weapon.id,defender_weapon.id,round(ascore,1),round(dscore,1),effect,jsonb_build_object('energy_cost',20,'burn_damage',burn_damage)) returning id into bid;
 end if;
 insert into public.battle_events(battle_id,actor_id,event_type,message,payload) values
  (bid,a.id,'attack',a.username||' нападна '||d.username,jsonb_build_object('weapon',coalesce(weapon.name,'Без оръжие')));
 if weapon.id is not null then insert into public.battle_events(battle_id,actor_id,event_type,message,payload) values(bid,a.id,'weapon',a.username||' използва '||weapon.name,jsonb_build_object('weapon_id',weapon.id)); end if;
 if effect='burn' then insert into public.battle_events(battle_id,actor_id,event_type,message,payload) values(bid,a.id,'special','🔥 Молотовът подпали противника',jsonb_build_object('extra_damage',burn_damage)); end if;
 insert into public.battle_events(battle_id,actor_id,event_type,message,payload) values(bid,case when won then a.id else d.id end,'result',(case when won then a.username else d.username end)||' спечели битката',jsonb_build_object('attacker_score',round(ascore,1),'defender_score',round(dscore,1),'respect',rep,'money',cash));
 insert into public.game_notifications(user_id,battle_id,notification_type,title,body) values
  (d.id,bid,'attacked','⚠️ Нападнаха те!',a.username||' те нападна'||case when weapon.id is not null then ' с '||weapon.name else '' end||'.'),
  (a.id,bid,'battle_result',case when won then '🏆 Победа!' else '💥 Загуба' end,'Битката срещу '||d.username||' приключи. Натисни, за да я отвориш.'),
  (d.id,bid,'battle_result',case when won then '💥 Загуба' else '🏆 Победа!' end,'Битката срещу '||a.username||' приключи. Натисни, за да я отвориш.');
 if weapon.id is not null and weapon.consumed_on_use then
  if weapon_qty<=1 then delete from public.inventory where user_id=a.id and item_id=weapon.id;
  else update public.inventory set quantity=quantity-1 where user_id=a.id and item_id=weapon.id; end if;
 end if;
 update public.profiles set level=greatest(level,1+floor(respect/25.0)::int) where id in(a.id,d.id);
 return jsonb_build_object('battle_id',bid,'won',won,'respect',rep,'money',cash,'attacker_score',round(ascore,1),'defender_score',round(dscore,1),'weapon',weapon.name,'special_effect',effect,'special_effect_value',burn_damage);
end $$;

