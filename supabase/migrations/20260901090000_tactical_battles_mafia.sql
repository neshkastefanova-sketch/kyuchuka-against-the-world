create table if not exists public.battle_events (
  id bigint generated by default as identity primary key,
  battle_id bigint not null references public.battles(id) on delete cascade,
  actor_id uuid references public.profiles(id),
  event_type text not null,
  message text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists battle_events_battle_id_idx on public.battle_events(battle_id,id);

create table if not exists public.game_notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  battle_id bigint references public.battles(id) on delete cascade,
  notification_type text not null,
  title text not null,
  body text not null,
  read_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists game_notifications_user_idx on public.game_notifications(user_id,read_at,created_at desc);

create table if not exists public.mafias (
  id bigint generated by default as identity primary key,
  name text not null unique,
  leader_gang_id bigint not null references public.gangs(id),
  reputation integer not null default 0,
  created_by uuid not null references public.profiles(id),
  created_at timestamptz not null default now()
);
create table if not exists public.mafia_gangs (
  mafia_id bigint not null references public.mafias(id) on delete cascade,
  gang_id bigint not null unique references public.gangs(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key(mafia_id,gang_id)
);
create table if not exists public.mafia_invites (
  id bigint generated by default as identity primary key,
  mafia_id bigint not null references public.mafias(id) on delete cascade,
  gang_id bigint not null references public.gangs(id) on delete cascade,
  invited_by uuid not null references public.profiles(id),
  status text not null default 'pending' check(status in ('pending','accepted','declined')),
  created_at timestamptz not null default now(),
  responded_at timestamptz,
  unique(mafia_id,gang_id)
);
create table if not exists public.mafia_wars (
  id bigint generated by default as identity primary key,
  challenger_mafia_id bigint not null references public.mafias(id),
  defender_mafia_id bigint not null references public.mafias(id),
  status text not null default 'planned' check(status in ('planned','open','finished','cancelled')),
  challenger_score integer not null default 0,
  defender_score integer not null default 0,
  winner_mafia_id bigint references public.mafias(id),
  starts_at timestamptz,
  ends_at timestamptz,
  created_at timestamptz not null default now(),
  check(challenger_mafia_id <> defender_mafia_id)
);

