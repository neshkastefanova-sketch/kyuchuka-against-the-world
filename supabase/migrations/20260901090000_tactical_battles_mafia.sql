create or replace function public.create_mafia(p_name text)
returns jsonb language plpgsql security definer set search_path='public' as $$
declare gm public.gang_members; mid bigint;
begin
 if auth.uid() is null then raise exception 'not authenticated'; end if;
 select * into gm from public.gang_members where user_id=auth.uid();
 if gm.user_id is null or gm.role<>'leader' then raise exception 'Само лидер на банда може да създаде Мафия.'; end if;
 if exists(select 1 from public.mafia_gangs where gang_id=gm.gang_id) then raise exception 'Бандата вече е в Мафия.'; end if;
 if length(trim(p_name))<3 then raise exception 'Името трябва да е поне 3 символа.'; end if;
 insert into public.mafias(name,leader_gang_id,created_by) values(trim(p_name),gm.gang_id,auth.uid()) returning id into mid;
 insert into public.mafia_gangs(mafia_id,gang_id) values(mid,gm.gang_id);
 return jsonb_build_object('id',mid,'name',trim(p_name),'leader_gang_id',gm.gang_id);
end $$;

create or replace function public.invite_mafia_gang(p_gang_id bigint)
returns jsonb language plpgsql security definer set search_path='public' as $$
declare gm public.gang_members; m public.mafias; iid bigint;
begin
 if auth.uid() is null then raise exception 'not authenticated'; end if;
 select * into gm from public.gang_members where user_id=auth.uid();
 select mm.* into m from public.mafias mm where mm.leader_gang_id=gm.gang_id;
 if gm.role<>'leader' or m.id is null then raise exception 'Само лидерската банда на Мафията може да кани.'; end if;
 if p_gang_id=gm.gang_id then raise exception 'Тази банда вече е лидерска.'; end if;
 if exists(select 1 from public.mafia_gangs where gang_id=p_gang_id) then raise exception 'Бандата вече е в Мафия.'; end if;
 insert into public.mafia_invites(mafia_id,gang_id,invited_by) values(m.id,p_gang_id,auth.uid())
 on conflict(mafia_id,gang_id) do update set status='pending',invited_by=excluded.invited_by,created_at=now(),responded_at=null returning id into iid;
 return jsonb_build_object('invite_id',iid,'mafia_id',m.id,'gang_id',p_gang_id);
end $$;

create or replace function public.respond_mafia_invite(p_invite_id bigint,p_accept boolean)
returns jsonb language plpgsql security definer set search_path='public' as $$
declare gm public.gang_members; inv public.mafia_invites; m public.mafias;
begin
 if auth.uid() is null then raise exception 'not authenticated'; end if;
 select * into gm from public.gang_members where user_id=auth.uid();
 if gm.user_id is null or gm.role<>'leader' then raise exception 'Само лидерът на поканената банда може да отговори.'; end if;
 select * into inv from public.mafia_invites where id=p_invite_id for update;
 if inv.id is null or inv.gang_id<>gm.gang_id or inv.status<>'pending' then raise exception 'Невалидна покана.'; end if;
 if p_accept then
  if exists(select 1 from public.mafia_gangs where gang_id=gm.gang_id) then raise exception 'Бандата вече е в Мафия.'; end if;
  insert into public.mafia_gangs(mafia_id,gang_id) values(inv.mafia_id,gm.gang_id);
  update public.mafia_invites set status='accepted',responded_at=now() where id=inv.id;
  select * into m from public.mafias where id=inv.mafia_id;
  return jsonb_build_object('accepted',true,'mafia_id',m.id,'name',m.name);
 else
  update public.mafia_invites set status='declined',responded_at=now() where id=inv.id;
  return jsonb_build_object('accepted',false);
 end if;
end $$;

create or replace function public.leave_mafia()
returns jsonb language plpgsql security definer set search_path='public' as $$
declare gm public.gang_members; mg public.mafia_gangs; m public.mafias; cnt int;
begin
 if auth.uid() is null then raise exception 'not authenticated'; end if;
 select * into gm from public.gang_members where user_id=auth.uid();
 if gm.user_id is null or gm.role<>'leader' then raise exception 'Само лидерът на бандата може да я извади от Мафия.'; end if;
 select * into mg from public.mafia_gangs where gang_id=gm.gang_id;
 if mg.gang_id is null then raise exception 'Бандата не е в Мафия.'; end if;
 select * into m from public.mafias where id=mg.mafia_id;
 if m.leader_gang_id=gm.gang_id then raise exception 'Лидерската банда не може да напусне. Първо трябва да предаде лидерството.'; end if;
 delete from public.mafia_gangs where mafia_id=mg.mafia_id and gang_id=gm.gang_id;
 select count(*) into cnt from public.mafia_gangs where mafia_id=mg.mafia_id;
 return jsonb_build_object('left',true,'remaining_gangs',cnt);
end $$;

